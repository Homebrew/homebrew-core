  license "GPL-3.0-only"

  bottle do
    rebuild 1
    sha256 cellar: :any_skip_relocation, all: "4c195f3132769a2c3f54d34585f5aaf9434f5b9c6d7f2f9d5cb05e8a3a060f5b"
  end

