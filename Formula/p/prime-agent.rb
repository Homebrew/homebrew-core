  def install
    system "cargo", "install", *std_cargo_args(path: "crates/pa-cli")
    libexec.install "prime-agent-runtime", "skills", "models.bundled.json", "mcp-services.bundled.json"

    venv = virtualenv_create(libexec/"venv", python3)
    venv.pip_install resources
    venv.pip_install libexec/"prime-agent-runtime"
    venv.pip_install libexec.glob("skills/*/pyproject.toml").map(&:dirname)

    bin.env_script_all_files libexec/"bin",
      PI_PACKAGE_DIR:            libexec,
      PRIME_AGENT_KERNEL_PYTHON: "${PRIME_AGENT_KERNEL_PYTHON:-#{opt_libexec}/venv/bin/python}"
  end

  test do
    ENV["PI_OFFLINE"] = "1"
    ENV["DO_NOT_TRACK"] = "1"

    assert_match version.to_s, shell_output("#{bin}/prime-agent --version")
    assert_kind_of Array, JSON.parse(shell_output("#{bin}/prime-agent doctor --json"))
    # Validates the bundled runtime and the default packages of the prebuilt kernel venv
    assert_match "kernel python: #{opt_libexec}/venv/bin/python",
                 shell_output("#{bin}/prime-agent --prime-agent-bootstrap")
  end
