      @mcp.tool
      def add(a: int, b: int) -> int:
          return a + b
    PYTHON

    port = free_port
    ENV["FASTMCP_STATELESS_HTTP"] = "1"
    pid = spawn bin/"fastmcp", "run", "server.py:mcp", "--transport=http", "--port=#{port}", "--no-banner"

