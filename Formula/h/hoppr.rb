  test do
    (testpath/"jq.json").write <<~JSON
      {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "components": [{ "type": "application", "name": "jq", "purl": "pkg:generic/jq@1.8.2" }]
      }
    JSON
    (testpath/"wget.json").write <<~JSON
      {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "components": [{ "type": "application", "name": "wget", "purl": "pkg:generic/wget@1.25.0" }]
      }
    JSON

    system bin/"hopctl", "merge", "--sbom=jq.json", "--sbom=wget.json", "--output-file=merged.json"
    merged = JSON.parse((testpath/"merged.json").read)
    expected_components = %w[pkg:generic/jq@1.8.2 pkg:generic/wget@1.25.0]
    assert_equal expected_components, merged["components"].map { |c| c["purl"] }
  end
