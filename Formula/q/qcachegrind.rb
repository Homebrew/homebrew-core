class Qcachegrind < Formula
  desc "Visualize data generated by Cachegrind and Calltree"
  homepage "https://apps.kde.org/kcachegrind/"
  url "https://download.kde.org/stable/release-service/26.08.0/src/kcachegrind-26.08.0.tar.xz"
  sha256 "760296956f12ced6bb51a6db2be813be425ee60bc204bd36a9c42a273e5ca0df"
  license "GPL-2.0-or-later"
  head "https://invent.kde.org/sdk/kcachegrind.git", branch: "master"

  # We don't match versions like 19.07.80 or 19.07.90 where the patch number
  # is 80+ (beta) or 90+ (RC), as these aren't stable releases.
  livecheck do
    url "https://download.kde.org/stable/release-service/"
    regex(%r{href=.*?v?(\d+\.\d+\.(?:(?![89]\d)\d+)(?:\.\d+)*)/?["' >]}i)
  end

  bottle do
    sha256 cellar: :any, arm64_tahoe:   "1739225cdd1db258f1e27da9a5abd2a17e108ccd5ab62f2a4a07330d154db104"
    sha256 cellar: :any, arm64_sequoia: "c6ca0ae5c01538c69a4c2c74676e1204e433ab2ca1b32d1c68bdb4f146e56482"
    sha256 cellar: :any, arm64_sonoma:  "baac74e313a556435619b85f5209b7fe1abf3532bda9fc86aeb2d9c92c72a814"
    sha256 cellar: :any, sonoma:        "bce725a0c9f5ecae2f585c47ee457d628b275c169d6a6799ca4d68f1477940a5"
    sha256 cellar: :any, arm64_linux:   "4460ca513c0a89c80c65b64e07ca6e4a51490979c4be35e2a1943578de821a0c"
    sha256 cellar: :any, x86_64_linux:  "a0bb83f38dedce580af1abad54e0fd2b71177e51e89e59271bf143b788e16b1b"
  end

  depends_on "graphviz"
  depends_on "qtbase"

  def install
    args = %w[-config release]
    if OS.mac?
      spec = (ENV.compiler == :clang) ? "macx-clang" : "macx-g++"
      args += %W[-spec #{spec}]
    end

    qt = Formula["qtbase"]
    system qt.opt_bin/"qmake", *args
    system "make"

    if OS.mac?
      prefix.install "qcachegrind/qcachegrind.app"
      bin.install_symlink prefix/"qcachegrind.app/Contents/MacOS/qcachegrind"
    else
      bin.install "qcachegrind/qcachegrind"
    end
  end
end
