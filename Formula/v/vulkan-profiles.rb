  def install
    # TODO: Remove stamp staging when upstream supports an existing Python environment.
    # https://github.com/KhronosGroup/Vulkan-Profiles/issues/1008
    venv = virtualenv_create(buildpath/"build/python-venv", python3)
    site_packages = Language::Python.site_packages(python3)
    pth_contents = "import site; site.addsitedir('#{formula_opt_libexec("pyinstaller")/site_packages}')\n"
    (venv.site_packages/"homebrew-pyinstaller.pth").write pth_contents
    build_backends = %w[flit-core poetry-core calver vcs-versioning setuptools-scm pathspec pluggy
                        tomlkit trove-classifiers hatchling hatch-vcs hatch-fancy-pypi-readme]
    venv.pip_install build_backends.map { |r| resource(r) }, build_isolation: false
    venv.pip_install resources.reject { |r| build_backends.include?(r.name) || r.name == "khronos-schemas" },
                     build_isolation: false
    (venv.root/"venv.stamp").write ""
    resource("khronos-schemas").stage do
      (buildpath/"schema").install Dir["vulkan/profiles-*.json"]
    end

    # fix dependency on no-longer-existing CMake files for jsoncpp
    inreplace "CMakeLists.txt",
              "find_package(jsoncpp REQUIRED CONFIG)",
              "find_package(PkgConfig REQUIRED QUIET)\npkg_search_module(jsoncpp REQUIRED jsoncpp)"
    inreplace "layer/CMakeLists.txt", "jsoncpp_static", "jsoncpp"
    inreplace "profiles/test/CMakeLists.txt", "jsoncpp_static", "jsoncpp"

    system "cmake", "-S", ".", "-B", "build",
                    "-DCMAKE_INSTALL_RPATH=#{rpath(target: formula_opt_lib("vulkan-loader"))}",
                    "-DPython3_EXECUTABLE=#{which("python3")}",
                    "-DVALIJSON_INSTALL_DIR=#{Formula["valijson"].prefix}",
                    "-DVULKAN_HEADERS_INSTALL_DIR=#{Formula["vulkan-headers"].prefix}",
                    "-DVULKAN_LOADER_INSTALL_DIR=#{Formula["vulkan-loader"].prefix}",
                    "-DVULKAN_UTILITY_LIBRARIES_INSTALL_DIR=#{Formula["vulkan-utility-libraries"].prefix}",
                    *std_cmake_args
    system "cmake", "--build", "build"
    system "cmake", "--install", "build"
  end

  def caveats
