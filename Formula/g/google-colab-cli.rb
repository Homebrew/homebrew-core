  def install
    inreplace "src/colab_cli/state.py", "enable_update_check: bool = True", "enable_update_check: bool = False"
    update_body = /^    auto_update\.check_for_updates\(quiet=False\).*?^    auto_update\.self_install\(\)/m
    inreplace "src/colab_cli/commands/utility.py" do |s|
      s.sub!(/"After checking, run 'pip install.*?"Linux only\."/m,
             '"In-place upgrades are disabled for Homebrew installations."')
      s.sub!(update_body, <<~PYTHON.chomp.gsub(/^/, "    "))
        if install:
            typer.echo("[colab] Run 'brew upgrade google-colab-cli' to update.", err=True)
            raise typer.Exit(code=1)
        auto_update.check_for_updates(quiet=False)
      PYTHON
    end
    install_hint = /^    import sys\n\n    if is_self_install_supported.*?^    return f"pip install --upgrade .*?"/m
    inreplace "src/colab_cli/auto_update.py", install_hint, '    return "brew upgrade google-colab-cli"'

    numpy_include = formula_opt_lib("numpy")/Language::Python.site_packages(python3)/"numpy/_core/include"
    ENV.prepend "CFLAGS", "-I#{numpy_include}"
    ENV["ZMQ_PREFIX"] = formula_opt_prefix("zeromq")

    without = %w[jeepney secretstorage] unless OS.linux?
    virtualenv_install_with_resources(without:)
  end

  test do
    code = "print('Hello from Colab')"
    (testpath/".config/colab-cli/history/brew.jsonl").write({ event_type: "execution", code: }.to_json + "\n")

    system bin/"colab", "log", "--session", "brew", "--output", "brew.ipynb"
    notebook = JSON.parse((testpath/"brew.ipynb").read)
    assert_equal [code], notebook.fetch("cells").find { |cell| cell["cell_type"] == "code" }.fetch("source")
    assert_match "brew upgrade google-colab-cli", shell_output("#{bin}/colab update --install 2>&1", 1)
  end
