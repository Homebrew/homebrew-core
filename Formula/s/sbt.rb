class Sbt < Formula
  desc "Build tool for Scala projects"
  homepage "https://www.scala-sbt.org/"
  url "https://github.com/sbt/sbt/releases/download/v2.1.1/sbt-2.1.1.tgz"
  sha256 "54f99416b027f201d881326075bf85f20680d8c3f2b09415584829e868b34999"
  license "Apache-2.0"
  compatibility_version 1

  # Upstream sometimes creates releases that use a stable tag (e.g., `v1.2.3`)
  # but are labeled as "pre-release" on GitHub.
  livecheck do
    url :stable
    strategy :github_latest
  end

  bottle do
    manifest_sha256 "44be2f05e29060fdc8d62e656da4a53c7c81c4d7c0b5fdc0a7a22714b5a8ae65"
    sha256 cellar: :any_skip_relocation, all: "f75a0374a1faf915d7d811e91ee3f0d73aee5b8ab92838036429e1d20e921bff"
  end

  depends_on "openjdk"

  allow_network_access! :test

  def install
    inreplace "bin/sbt" do |s|
      s.gsub! 'etc_sbt_opts_file="/etc/sbt/sbtopts"', "etc_sbt_opts_file=\"#{etc}/sbtopts\""
      s.gsub! "/etc/sbt/sbtopts", "#{etc}/sbtopts"
    end

    libexec.install "bin"
    etc.install "conf/sbtopts"

    # Removes:
    # 1. `sbt.bat` (Windows-only)
    # 2. `sbtn` (pre-compiled native binary)
    # 3. `sbtn-universal-apple-darwin` (universal binary)
    (libexec/"bin").glob("sbt{.bat,n-x86_64*,n-aarch64*,n-universal-apple-darwin}").map(&:unlink)
    (bin/"sbt").write_env_script libexec/"bin/sbt", Language::Java.overridable_java_home_env
  end

  def caveats
    <<~EOS
      You can use $SBT_OPTS to pass additional JVM options to sbt.
      Project specific options should be placed in .sbtopts in the root of your project.
      Global settings should be placed in #{etc}/sbtopts

      The installation does not include `sbtn`.
    EOS
  end

  test do
    ENV.append "_JAVA_OPTIONS", "-Dsbt.log.noformat=true"
    touch testpath/"build.sbt"
    system bin/"sbt", "about"
    assert_match version.to_s, shell_output("#{bin}/sbt --version")
  end
end
